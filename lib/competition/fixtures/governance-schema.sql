-- Isolated supporting schema. Unrelated legacy RPCs are dependency contracts;
-- assessment scoring and all market/SME/sponsor governance use real definitions.
create role anon; create role authenticated;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;
      create table profiles(id uuid primary key,role text,status text,country text);
      create table curricula(id uuid primary key,code text,country text);
      create table tenants(id uuid primary key,country text,code text);
      create table tenant_memberships(user_id uuid,tenant_id uuid,status text);
      create table sponsor_profiles(id uuid primary key default gen_random_uuid(),user_id uuid,organization_name text,contact_name text,status text,created_at timestamptz default now(),updated_at timestamptz default now());
      create table curriculum_nodes(id uuid primary key,curriculum_id uuid,education_level text,is_active boolean,source_grade_code text,canonical_grade_code text,subject_code text,grade_code text);
      create table classes(id uuid primary key,curriculum_id uuid,tenant_id uuid);
      create table class_memberships(id uuid primary key,class_id uuid,student_user_id uuid,status text);
      create table question_banks(id uuid primary key,tenant_id uuid);
      create table assignments(id uuid primary key,class_id uuid,assessment_id uuid,status text,recipient_mode text,opens_at timestamptz,due_at timestamptz);
      create table question_bank_items(id uuid primary key,question_id uuid,bank_id uuid);
      create table question_media(question_id uuid);
      create table learning_events(id uuid primary key,curriculum_node_id uuid);
      create table mastery_records(id uuid primary key,curriculum_node_id uuid);
      create table source_documents(id uuid primary key,tenant_id uuid,uploaded_by uuid,title text,checksum text,rights_confirmed boolean,mime_type text,storage_bucket text,storage_path text,metadata jsonb,status text default 'UPLOADED',updated_at timestamptz default now());
      create table competitions(id uuid primary key default gen_random_uuid(),sponsor_id uuid,assessment_id uuid,created_by uuid,title text,description text,status text,updated_at timestamptz default now());
      create table competition_stages(id uuid primary key,competition_id uuid);
      create table competition_rounds(id uuid primary key,stage_id uuid,assessment_id uuid);
      create table competition_results(competition_id uuid,score int);
      create table competition_sponsors(competition_id uuid,committed_amount int);
      create table competition_teams(id uuid primary key,competition_id uuid);
      create table competition_team_members(id uuid primary key,team_id uuid);
      create table content_import_batches(id uuid primary key,generation_spec jsonb,imported_by uuid);
create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
create table assignment_targets(assignment_id uuid,student_user_id uuid,membership_id uuid,status text);
create schema storage;
create schema extensions;
create extension pgcrypto with schema extensions;
create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);
alter table storage.objects enable row level security;
grant usage on schema storage to authenticated;
grant select,insert on storage.objects to authenticated;
