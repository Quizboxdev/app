#!/usr/bin/env python3
"""Tracker C7: find what exists ONLY on the hosted production database, so a new database can be built from the repository alone.

Some helpers and tables were created by hand on production and never written into a migration (for example public.qb_is_platform_admin(), qb_can_manage_class(),
public.system_events). The migration chain therefore stops on any empty database. This writes one read-only query for the Supabase SQL editor. It lists every
function and table in the application schemas that the migrations do NOT create, with the real definition (pg_get_functiondef for functions; a rebuilt
CREATE TABLE for tables). The owner runs it once and saves the output; the definitions then go into a bootstrap migration guarded with "only if missing".

  python scripts/release/production_only_objects.py   ->   docs/release/engine/24_production_only_objects.sql
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "docs" / "release" / "engine" / "17_production_missing_objects.sql"
OUT = REPO / "docs" / "release" / "engine" / "24_production_only_objects.sql"

def main():
    rows = re.findall(r"\('(function|table|view)','([a-z_0-9]+)','([A-Za-z_0-9]+)'", SRC.read_text(encoding="utf-8"))
    fns = sorted({f"{s}.{n}" for k, s, n in rows if k == "function"})
    tbs = sorted({f"{s}.{n}" for k, s, n in rows if k in ("table", "view")})
    fvals = ",\n".join(f"  ('{x}')" for x in fns); tvals = ",\n".join(f"  ('{x}')" for x in tbs)
    sql = f"""-- Production-only objects (read-only). Generated by scripts/release/production_only_objects.py from the {len(fns)} functions and {len(tbs)} tables the migrations create.
-- Run in the Supabase SQL editor with "No limit". It returns ONE column, ddl: every function and table in the application schemas that the migrations do NOT create.
-- Copy the whole ddl column (all rows) into the file  docs/release/engine/production_only_objects.sql  and tell me. Nothing is changed by running it.
with known_fn(name) as (values
{fvals}
), known_tb(name) as (values
{tvals}
),
fns as (
  select n.nspname || '.' || p.proname as name, pg_get_functiondef(p.oid) || ';' as ddl
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where (n.nspname = 'public' or n.nspname like 'quizbox\\_%') and p.prokind = 'f'
     and not exists (select 1 from known_fn k where k.name = n.nspname || '.' || p.proname)
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
tbs as (
  select n.nspname || '.' || c.relname as name,
         'create table if not exists ' || quote_ident(n.nspname) || '.' || quote_ident(c.relname) || ' (' || chr(10) ||
         (select string_agg('  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod) ||
                  coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), '') || case when a.attnotnull then ' not null' else '' end, ',' || chr(10) order by a.attnum)
            from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
           where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped) ||
         coalesce((select ',' || chr(10) || '  ' || pg_get_constraintdef(k.oid) from pg_constraint k where k.conrelid = c.oid and k.contype = 'p'), '') || chr(10) || ');' as ddl
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where (n.nspname = 'public' or n.nspname like 'quizbox\\_%') and c.relkind = 'r'
     and not exists (select 1 from known_tb k where k.name = n.nspname || '.' || c.relname)
)
select '-- TABLE ' || name || chr(10) || ddl as ddl from tbs
union all
select '-- FUNCTION ' || name || chr(10) || ddl from fns
order by 1;
"""
    OUT.write_text(sql, encoding="utf-8")
    print(f"{len(fns)} known functions, {len(tbs)} known tables -> {OUT.relative_to(REPO)}")

if __name__ == "__main__":
    main()
