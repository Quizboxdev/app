#!/usr/bin/env python3
"""Phase 4 (app-ready): write docs/api/MOBILE_API_CONTRACT.md, the list of backend calls a native or PWA client may make, generated from the code.

Every client call in this app is either a Supabase RPC (database function, rules enforced in the database), a direct table read under row-level
security, or one of a few Next.js API routes. A mobile app uses the same Supabase project and the same signed-in session token, so the contract is
exactly this list. Re-run after adding calls:  python scripts/release/api_contract.py
"""
import re
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "api" / "MOBILE_API_CONTRACT.md"
ALLOW = REPO / "lib" / "operations" / "public-rpc-allowlist.ts"

def area(path: str) -> str:
    p = path.replace("\\", "/")
    for key, name in (("challenge", "Challenges"), ("admin", "Admin and support"), ("sme", "Reviewers (SME)"), ("review", "Reviewers (SME)"), ("teacher", "Teacher"), ("school", "School"),
                      ("sponsor", "Sponsor"), ("competition", "Competitions"), ("practice", "Learner"), ("practise", "Learner"), ("student", "Learner"),
                      ("assessment", "Learner"), ("learning", "Learner"), ("curriculum", "Curriculum (all roles)"), ("auth", "Account and sign-in"),
                      ("account", "Account and sign-in"), ("public", "Public (no sign-in)"), ("market", "Markets"), ("owner", "Admin and support"),
                      ("notification", "Notifications"), ("platform", "Platform")):
        if key in p.lower(): return name
    return "Shared"

def main():
    rpcs = defaultdict(set); tables = defaultdict(set)
    for f in list((REPO / "lib").rglob("*.ts")) + list((REPO / "components").rglob("*.tsx")) + list((REPO / "app").rglob("*.tsx")):
        if f.name.endswith(".test.ts"): continue
        src = f.read_text(encoding="utf-8", errors="replace"); rel = f.relative_to(REPO).as_posix()
        # Every database function the app calls is named qb_...; wrappers (rpc<T>(...), callRpc, marketSetup actions) all pass that literal.
        for m in re.finditer(r"""["'`]((?:qb|challenge)_[a-z_0-9]+)["'`]""", src): rpcs[m.group(1)].add(rel)
        for m in re.finditer(r"""\.from\(\s*["'`]([a-z_0-9]+)["'`]\s*\)\s*\.(select|insert|update|upsert|delete)""", src): tables[(m.group(1), m.group(2))].add(rel)
    public = set(re.findall(r'"(qb_[a-z_0-9]+)"', ALLOW.read_text(encoding="utf-8"))) if ALLOW.exists() else set()
    routes = sorted(p.relative_to(REPO / "app").as_posix().replace("/route.ts", "") for p in (REPO / "app" / "api").rglob("route.ts"))
    by_area = defaultdict(list)
    for name, files in rpcs.items(): by_area[area(sorted(files)[0])].append((name, sorted(files)))
    lines = ["# QuizBox API contract for web, PWA and native apps", "",
             "Generated by `scripts/release/api_contract.py` from the code. Do not edit by hand; re-run the script after adding a call.", "",
             "## How a client connects",
             "- **One backend:** the Supabase project behind www.quizbox.io. A native app uses the Supabase client library for its platform (JavaScript, Dart/Flutter, Swift or Kotlin) with the same project URL and public (anon) key the web app uses.",
             "- **Sign-in:** Supabase Auth (email and password). Every call below runs as the signed-in user; the database enforces who may do what. A client cannot widen its own access.",
             "- **Calls:** `rpc(name, args)` for the functions listed here, plus the row-level-security table reads listed after them. Error codes come back as `QB_...` strings; `lib/errors.ts` holds the plain-language messages to show.",
             "- **Public calls** (no sign-in) are limited to the public allow-list: " + (", ".join(f"`{p}`" for p in sorted(public)) or "none") + ".",
             "- **Versioning rule:** a function's name and arguments are never changed in place. A breaking change gets a new function name (for example `_v2`), and the old one stays until no supported app version uses it.",
             "- **Server routes** (`/api/...`) below use the web session cookie today. They are admin and sponsor tools; a learner or teacher app does not need them.", ""]
    total = 0
    for a in sorted(by_area):
        items = sorted(by_area[a]); total += len(items)
        lines += [f"## {a} ({len(items)} functions)", "", "| Function | Called from |", "|---|---|"]
        lines += [f"| `{n}` | {', '.join(f'`{x}`' for x in fs[:3])}{' …' if len(fs) > 3 else ''} |" for n, fs in items]
        lines.append("")
    lines += ["## Direct table access (row-level security applies)", "", "| Table | Operation | Called from |", "|---|---|---|"]
    lines += [f"| `{t}` | {op} | {', '.join(f'`{x}`' for x in sorted(fs)[:2])} |" for (t, op), fs in sorted(tables.items())]
    lines += ["", "## Server routes", "", *[f"- `/{r}`" for r in routes], "", f"**Totals:** {total} functions, {len(tables)} table operations, {len(routes)} server routes."]
    OUT.parent.mkdir(parents=True, exist_ok=True); OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{total} functions, {len(tables)} table operations, {len(routes)} routes -> {OUT.relative_to(REPO)}")

if __name__ == "__main__":
    main()
