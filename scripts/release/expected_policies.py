#!/usr/bin/env python3
"""Phase 0 step 2: the second production check. After tables and functions match (17_production_missing_objects), this checks what that query cannot see:
  A. triggers the migrations create that are missing in production
  B. row-level-security policies the migrations create that are missing in production
  C. every table in the application schemas where row-level security is switched OFF (independent of the repository)
  D. tables and views the browser roles (anon, authenticated) can still TRUNCATE (the grant-hardening migration removes this)
  E. the functions that this week's apply pack adds, present or missing

  python scripts/release/expected_policies.py   ->  docs/release/engine/20_production_policy_trigger_check.sql   (read-only)

Triggers and policies created inside loops (format(...) in a DO block) cannot be listed from the text; check C covers that gap for RLS.
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MIG = REPO / "supabase" / "migrations"
OUT = REPO / "docs" / "release" / "engine" / "20_production_policy_trigger_check.sql"
I = r'"?([a-z_][a-z0-9_]*)"?'
Q = rf"(?:{I}\.)?{I}"
P_TRIG = re.compile(rf"create\s+(?:or\s+replace\s+)?(?:constraint\s+)?trigger\s+{I}\s+(?:before|after|instead\s+of)\s+[^;]*?\bon\s+{Q}", re.I | re.S)
P_POL = re.compile(rf"create\s+policy\s+(?:\"([^\"]+)\"|{I})\s+on\s+{Q}", re.I)
P_DROP_TRIG = re.compile(rf"drop\s+trigger\s+(?:if\s+exists\s+)?{I}\s+on\s+{Q}", re.I)
P_DROP_POL = re.compile(rf"drop\s+policy\s+(?:if\s+exists\s+)?(?:\"([^\"]+)\"|{I})\s+on\s+{Q}", re.I)

def clean(sql):
    sql = re.sub(r"/\*.*?\*/", "", sql, flags=re.S)
    return "\n".join("" if l.strip().startswith("--") else l.split("--", 1)[0] for l in sql.splitlines())

def main():
    trig, pol = {}, {}
    for f in sorted(MIG.glob("*.sql")):
        sql = clean(f.read_text(encoding="utf-8", errors="replace")); ev = []
        for m in P_TRIG.finditer(sql): ev.append((m.start(), "add", "t", (m.group(2) or "public", m.group(3), m.group(1))))
        for m in P_DROP_TRIG.finditer(sql): ev.append((m.start(), "drop", "t", (m.group(2) or "public", m.group(3), m.group(1))))
        for m in P_POL.finditer(sql): ev.append((m.start(), "add", "p", (m.group(3) or "public", m.group(4), m.group(1) or m.group(2))))
        for m in P_DROP_POL.finditer(sql): ev.append((m.start(), "drop", "p", (m.group(3) or "public", m.group(4), m.group(1) or m.group(2))))
        for _, op, kind, key in sorted(ev):
            d = trig if kind == "t" else pol
            if op == "add": d[key] = f.name
            else: d.pop(key, None)
    rows_t = [f"  ('{s}','{t}','{n}','{m}')" for (s, t, n), m in sorted(trig.items(), key=lambda kv: (kv[1], kv[0])) if s not in ("auth", "storage")]
    rows_p = [f"  ('{s}','{t}','{n.replace(chr(39), chr(39) * 2)}','{m}')" for (s, t, n), m in sorted(pol.items(), key=lambda kv: (kv[1], kv[0])) if s not in ("auth", "storage")]
    apply_fns = ["qb_owner_batch_preview", "qb_owner_approve_batch", "qb_owner_revoke_batch_approval", "qb_my_access", "qb_admin_set_free_allowance", "qb_admin_grant_subscription",
                 "qb_admin_grant_subscription_email", "qb_admin_revoke_subscription", "qb_admin_access_overview", "qb_topic_label", "qb_label_is_code", "qb_staff_practice_preview"]
    sql = f"""-- Second production check (read-only). Generated by scripts/release/expected_policies.py from {len(list(MIG.glob('*.sql')))} migrations.
-- Set the editor to "No limit", run, export as CSV. One result set; the 'check' column says what each row is. Zero rows in A, B, C, D and E = clean.
with exp_trig(schema_name, table_name, name, introduced_in) as (values
{",".join(chr(10) + r for r in rows_t).lstrip(chr(10)) if rows_t else "  ('x','x','x','x')"}
), exp_pol(schema_name, table_name, name, introduced_in) as (values
{",".join(chr(10) + r for r in rows_p).lstrip(chr(10)) if rows_p else "  ('x','x','x','x')"}
), apply_fns(name) as (values {",".join(f"('{n}')" for n in apply_fns)})
select 'A missing trigger' as "check", introduced_in as detail, schema_name || '.' || table_name || ' :: ' || name as object
  from exp_trig e where exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = e.schema_name and c.relname = e.table_name)
   and not exists (select 1 from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
                    where n.nspname = e.schema_name and c.relname = e.table_name and t.tgname = e.name and not t.tgisinternal)
union all
select 'B missing policy', introduced_in, schema_name || '.' || table_name || ' :: ' || name
  from exp_pol e where exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = e.schema_name and c.relname = e.table_name)
   and not exists (select 1 from pg_policies p where p.schemaname = e.schema_name and p.tablename = e.table_name and p.policyname = e.name)
union all
select 'C row-level security OFF', 'table has no RLS', n.nspname || '.' || c.relname
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
 where c.relkind in ('r', 'p') and (n.nspname = 'public' or n.nspname like 'quizbox\\_%') and not c.relrowsecurity
union all
select 'D browser role can TRUNCATE', r.rolname, n.nspname || '.' || c.relname
  from pg_class c join pg_namespace n on n.oid = c.relnamespace cross join (select rolname from pg_roles where rolname in ('anon', 'authenticated')) r
 where c.relkind in ('r', 'p') and (n.nspname = 'public' or n.nspname like 'quizbox\\_%') and has_table_privilege(r.rolname, c.oid, 'TRUNCATE')
union all
select 'E apply-pack function missing', 'public', a.name from apply_fns a
 where not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = a.name)
order by 1, 3;
"""
    OUT.write_text(sql, encoding="utf-8")
    print(f"{len(rows_t)} triggers, {len(rows_p)} policies -> {OUT.relative_to(REPO)}")

if __name__ == "__main__":
    main()
