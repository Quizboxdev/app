#!/usr/bin/env python3
"""Phase 0 (production truth): list every schema, table, view and function the repository's migration chain creates, and write one SQL query
that the owner runs in the Supabase SQL editor to see which of them are MISSING in production, with the migration that introduces each.

  python scripts/release/expected_objects.py      -> docs/release/engine/17_production_missing_objects.sql

Objects dropped by a later migration are left out. Read-only query; it changes nothing.
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MIG = REPO / "supabase" / "migrations"
OUT = REPO / "docs" / "release" / "engine" / "17_production_missing_objects.sql"

ident = r'"?([a-z_][a-z0-9_]*)"?'
qual = rf"(?:{ident}\.)?{ident}"
P_SCHEMA = re.compile(rf"create\s+schema\s+(?:if\s+not\s+exists\s+)?{ident}", re.I)
P_TABLE = re.compile(rf"create\s+(?:unlogged\s+)?table\s+(?:if\s+not\s+exists\s+)?{qual}", re.I)
P_VIEW = re.compile(rf"create\s+(?:or\s+replace\s+)?(?:materialized\s+)?view\s+(?:if\s+not\s+exists\s+)?{qual}", re.I)
P_FUNC = re.compile(rf"create\s+(?:or\s+replace\s+)?function\s+{qual}\s*\(", re.I)
P_DROP_T = re.compile(rf"drop\s+(?:table|view|materialized\s+view)\s+(?:if\s+exists\s+)?{qual}", re.I)
P_DROP_F = re.compile(rf"drop\s+function\s+(?:if\s+exists\s+)?{qual}\s*\(", re.I)
P_DROP_S = re.compile(rf"drop\s+schema\s+(?:if\s+exists\s+)?{ident}", re.I)

def strip_comments(sql):
    sql = re.sub(r"/\*.*?\*/", "", sql, flags=re.S)
    return "\n".join(l.split("--", 1)[0] if not l.strip().startswith("--") else "" for l in sql.splitlines())

def main():
    objs = {}  # (kind, schema, name) -> migration
    for f in sorted(MIG.glob("*.sql")):
        sql = strip_comments(f.read_text(encoding="utf-8", errors="replace"))
        events = []
        for kind, pat in (("schema", P_SCHEMA), ("table", P_TABLE), ("view", P_VIEW), ("function", P_FUNC)):
            for m in pat.finditer(sql):
                if kind == "schema": key = ("schema", m.group(1), "")
                else: key = (kind, m.group(1) or "public", m.group(2))
                events.append((m.start(), "add", key))
        for pat, kinds in ((P_DROP_T, ("table", "view")), (P_DROP_F, ("function",)), (P_DROP_S, ("schema",))):
            for m in pat.finditer(sql):
                for k in kinds:
                    key = ("schema", m.group(1), "") if k == "schema" else (k, m.group(1) or "public", m.group(2))
                    events.append((m.start(), "drop", key))
        for _, op, key in sorted(events):
            if op == "add": objs.setdefault(key, f.name)
            else: objs.pop(key, None)
    rows = []
    for (kind, schema, name), mig in sorted(objs.items(), key=lambda kv: (kv[1], kv[0])):
        if schema in ("auth", "storage", "extensions", "pg_catalog"): continue
        rows.append(f"  ('{kind}','{schema}','{name}','{mig}')")
    head = f"""-- Phase 0, production truth: which objects that the repository's migrations create are MISSING in this database.
-- Generated by scripts/release/expected_objects.py from {len(list(MIG.glob('*.sql')))} migrations ({len(rows)} objects). Read-only: changes nothing.
-- Run it in the Supabase SQL editor (set "No limit"), then Export -> CSV and send the file. Zero rows = schema objects match the repository.
with expected(kind, schema_name, object_name, introduced_in) as (values
"""
    tail = """
)
select e.introduced_in, e.kind, e.schema_name || coalesce('.' || nullif(e.object_name, ''), '') as object
from expected e
where case e.kind
  when 'schema'   then not exists (select 1 from pg_namespace n where n.nspname = e.schema_name)
  when 'function' then not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = e.schema_name and p.proname = e.object_name)
  else to_regclass(quote_ident(e.schema_name) || '.' || quote_ident(e.object_name)) is null
end
order by e.introduced_in, e.kind, object;
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(head + ",\n".join(rows) + tail, encoding="utf-8")
    print(f"{len(rows)} expected objects -> {OUT.relative_to(REPO)}")

if __name__ == "__main__":
    main()
